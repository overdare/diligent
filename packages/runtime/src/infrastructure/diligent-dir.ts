// @summary Manages .diligent directory structure with paths and gitignore setup
import { mkdir, stat } from "node:fs/promises";
import { join } from "node:path";
import { migrateLegacyMemoryStore } from "../memory/legacy";

export const DEFAULT_STORAGE_NAMESPACE = "diligent";

export function resolveStorageNamespace(env: NodeJS.ProcessEnv = process.env): string {
  const value = env.DILIGENT_STORAGE_NAMESPACE?.trim().toLowerCase();
  if (!value) return DEFAULT_STORAGE_NAMESPACE;
  if (!/^[a-z0-9-]+$/.test(value)) {
    throw new Error(`Invalid DILIGENT_STORAGE_NAMESPACE: ${value}`);
  }
  return value;
}

export function resolveProjectDirName(env: NodeJS.ProcessEnv = process.env): string {
  return `.${resolveStorageNamespace(env)}`;
}

export interface DiligentPaths {
  root: string;
  sessions: string;
  memory: string;
  skills: string;
  images: string;
}

export function resolvePaths(projectRoot: string, env: NodeJS.ProcessEnv = process.env): DiligentPaths {
  const root = join(projectRoot, resolveProjectDirName(env));
  return {
    root,
    sessions: join(root, "sessions"),
    memory: join(root, "memory"),
    skills: join(root, "skills"),
    images: join(root, "images"),
  };
}

const GITIGNORE_COMMENT = "# Sessions and memory are machine-local, not version-controlled";
const GITIGNORE_CONTENT = `# Auto-generated by diligent
${GITIGNORE_COMMENT}
sessions/
memory/
images/
logs/
`;

// Projects created before the knowledge → memory rename still carry these on disk.
const LEGACY_GITIGNORE_LINES = new Map([
  ["# Sessions and knowledge are machine-local, not version-controlled", GITIGNORE_COMMENT],
  ["knowledge/", "memory/"],
]);

async function ensureDir(path: string): Promise<void> {
  const existing = await stat(path).catch((error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });

  if (existing) {
    if (existing.isDirectory()) return;
    throw new Error(`Expected directory but found a file: ${path}`);
  }

  await mkdir(path, { recursive: true });
}

async function ensureGitignore(path: string): Promise<void> {
  const file = Bun.file(path);
  if (!(await file.exists())) {
    await Bun.write(path, GITIGNORE_CONTENT);
    return;
  }
  const content = await file.text();
  const migrated = content
    .split("\n")
    .map((line) => LEGACY_GITIGNORE_LINES.get(line) ?? line)
    .join("\n");
  if (migrated !== content) await Bun.write(path, migrated);
}

export async function ensureDiligentDir(
  projectRoot: string,
  env: NodeJS.ProcessEnv = process.env,
): Promise<DiligentPaths> {
  const paths = resolvePaths(projectRoot, env);
  await ensureDir(paths.sessions);
  await ensureDir(paths.memory);
  await ensureDir(paths.skills);
  await ensureDir(paths.images);
  await migrateLegacyMemoryStore(paths.root, paths.memory);
  await ensureGitignore(join(paths.root, ".gitignore"));

  return paths;
}
