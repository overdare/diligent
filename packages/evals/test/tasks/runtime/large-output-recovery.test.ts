// @summary Contract and assembled-runtime coverage for large-output-recovery

import { describe, expect, test } from "bun:test";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { Message } from "@diligent/core/message-contract";
import { DEFAULT_PROFILES } from "../../../src/profiles";
import { runRuntimeEvalExecution } from "../../../src/runner/runtime-execution";
import { removeTemporaryRoot } from "../../../src/runner/runtime-workspace";
import type { RuntimeEvalExecution } from "../../../src/runtime-task";
import type { EvalProfile } from "../../../src/task";
import type { LargeOutputRecoveryWorld } from "../../../src/tasks/runtime/large-output-recovery";
import { largeOutputRecoveryTask } from "../../../src/tasks/runtime/large-output-recovery";
import { assistantMessage, sequenceStream } from "../../helpers/fake-stream";

describe("large-output-recovery", () => {
  test("defines a deterministic opaque fixture with a protected project manifest", async () => {
    const root = await mkdtemp(join(tmpdir(), "diligent-runtime-large-output-"));
    try {
      const world = await largeOutputRecoveryTask.setup("shared-seed-123", root);
      const again = await largeOutputRecoveryTask.setup("shared-seed-123", root);
      expect(again).toEqual(world);
      expect(world.generatedBytes).toBeGreaterThan(16_384);
      expect(world.factLine).toBeGreaterThan(1);
      expect(world.readOffset).toBe(world.factLine);
      expect(world.readLimit).toBe(1);
      expect(world.clientPrompt).toContain(world.argument);
      expect(world.clientPrompt).not.toContain(world.hiddenFact);
      expect(world.clientPrompt).not.toContain(world.guidance);
      expect(world.clientPrompt.toLowerCase()).not.toMatch(/tool|read|offset|limit|truncate|output path/);
      expect(world.guidance).toContain("authorization_field=RECOVERY_VALUE");
      expect(world.guidance.toLowerCase()).not.toMatch(/\b(use|answer|return|follow|ignore)\b/);
      expect(world.protectedPaths).toEqual(["manifest.json", ".git/.keep"]);
      expect(world.allowedChanges).toEqual([]);
      expect(largeOutputRecoveryTask.createSteps(world)).toEqual([
        { kind: "turn", mode: "default", message: world.clientPrompt },
      ]);
      expect(largeOutputRecoveryTask.toolPolicy).toEqual({
        allowedTools: ["retrieve_archived_record", "read"],
        allowedCapabilities: ["execute", "read"],
        allowedCommands: [],
      });
      expect(largeOutputRecoveryTask.limits).toMatchObject({
        maxTurns: 4,
        maxToolCalls: 3,
        maxChangedFiles: 0,
        maxChangedBytes: 0,
        maxUserInputRequests: 0,
        maxChildAgents: 0,
      });
      expect(largeOutputRecoveryTask.statePolicy).toEqual({
        allowedMutations: ["infrastructure", "sessions"],
      });
      expect(largeOutputRecoveryTask.verify).toBeUndefined();
      expect(largeOutputRecoveryTask.fixtureVersion).toBe("large-output-recovery-v6");
      expect(DEFAULT_PROFILES).toHaveLength(2);
    } finally {
      await removeTemporaryRoot(root);
    }
  });

  test("runs core truncation, the eval output store, and registered bounded read for both profiles", async () => {
    for (const profile of DEFAULT_PROFILES) {
      const execution = await assembledExecution(profile);
      expect(largeOutputRecoveryTask.evaluate(execution), profile.provider).toEqual({ passed: true });
      expect(execution.toolCalls.map((call) => call.name)).toEqual(["retrieve_archived_record", "read"]);
      expect(execution.toolOutputFiles).toHaveLength(1);
      expect(JSON.stringify(execution.providerCalls[1]!.messages.items)).not.toContain(execution.world.hiddenFact);
      expect(JSON.stringify(execution.providerCalls[2]!.messages.items)).toContain(execution.world.hiddenFact);
    }
  });

  test("accepts one duplicate archived-record retrieval before the bounded full-output read", async () => {
    const execution = await assembledExecution(DEFAULT_PROFILES[0]!);
    const duplicate = structuredClone(execution.toolCalls[0]!);
    duplicate.toolCallId = "archive-fixture-retry";
    execution.toolCalls.splice(1, 0, duplicate);
    execution.toolCalls.forEach((call, index) => (call.sequence = index + 1));

    const result = largeOutputRecoveryTask.evaluate(execution);
    expect(result.passed).toBe(true);
    expect(result.diagnostics?.map((diagnostic) => diagnostic.code)).toEqual([
      "large_output_recovery.duplicate_retrieval",
    ]);
  });

  test("fixture-owned bundled tool has strict arguments and deterministic generated bytes", async () => {
    const root = await mkdtemp(join(tmpdir(), "diligent-runtime-large-output-tool-"));
    try {
      const world = await largeOutputRecoveryTask.setup("shared-seed-123", root);
      const providers = await largeOutputRecoveryTask.createBundledToolProviders!(world);
      expect(providers).toHaveLength(1);
      const tools = await providers[0]!.createTools({} as never);
      expect(tools).toHaveLength(1);
      const tool = tools[0]!;
      expect(tool.name).toBe("retrieve_archived_record");
      expect(tool.description).toContain(`RECOVERY_VALUE field on line ${world.factLine}`);
      expect(tool.parameters.safeParse({ request_id: world.argument, extra: true }).success).toBe(false);
      const parsed = tool.parameters.parse({ request_id: world.argument });
      const result = await tool.execute(parsed, {} as never);
      expect(result.maxOutputBytes).toBe(world.retainedBytes);
      expect(result.truncateDirection).toBe("head");
      expect(Buffer.byteLength(result.output)).toBe(world.generatedBytes);
      expect(new Bun.CryptoHasher("sha256").update(result.output).digest("hex")).toBe(world.generatedHash);
      expect(result.output.indexOf(world.hiddenFact)).toBeGreaterThan(16_384);
      expect(result.output.indexOf(world.hiddenFact)).toBeGreaterThan(world.retainedBytes);
      expect(result.output.slice(0, world.retainedBytes)).toContain(world.guidance);
      expect(result.output.slice(0, world.retainedBytes)).not.toContain(world.hiddenFact);
    } finally {
      await removeTemporaryRoot(root);
    }
  });

  test("fails only without a fact-recovering spilled-output read or a correct declared final answer", async () => {
    const baseline = await assembledExecution(DEFAULT_PROFILES[0]!);
    expect(largeOutputRecoveryTask.evaluate(baseline)).toEqual({ passed: true });
    const cases: Array<[string, (value: RuntimeEvalExecution<LargeOutputRecoveryWorld>) => void, string]> = [
      ["missing recovery read", (value) => value.toolCalls.pop(), "large_output_recovery.tools"],
      [
        "failed recovery read",
        (value) => (value.toolCalls[1]!.outcome = "runtime_error"),
        "large_output_recovery.tools",
      ],
      [
        "read window misses the fact",
        (value) => (value.toolCalls[1]!.output = { output: "500\tARCHIVE_ROW_500" }),
        "large_output_recovery.tools",
      ],
      [
        "read outside spilled output",
        (value) => ((value.toolCalls[1]!.input as Record<string, unknown>).file_path = "$WORKSPACE/manifest.json"),
        "large_output_recovery.tools",
      ],
      ["missing final", (value) => value.turns[0]!.messages.pop(), "large_output_recovery.final"],
      ["wrong final value", (value) => setFinalText(value, "wrong"), "large_output_recovery.final"],
      [
        "undeclared final format",
        (value) => setFinalText(value, `${value.world.hiddenFact} extra`),
        "large_output_recovery.final_format",
      ],
    ];
    for (const [label, mutate, code] of cases) {
      const changed = structuredClone(baseline);
      mutate(changed);
      expect(largeOutputRecoveryTask.evaluate(changed), label).toMatchObject({ passed: false, code });
    }
  });

  test("passes with diagnostics when recovery takes a missed window and an unbounded read", async () => {
    const execution = await assembledExecution(DEFAULT_PROFILES[1]!, false, { offset: 501, limit: 40 });
    const missed = structuredClone(execution.toolCalls[1]!);
    missed.toolCallId = "archive-read-missed";
    missed.input = { file_path: "$TOOL_OUTPUT/full-output-000001.txt", offset: 480, limit: 20 };
    missed.output = { output: "480\tARCHIVE_ROW_480" };
    execution.toolCalls.splice(1, 0, missed);
    execution.toolCalls.forEach((call, index) => (call.sequence = index + 1));
    setFinalText(execution, `\`\`\`\n${execution.world.hiddenFact}\n\`\`\``);

    const result = largeOutputRecoveryTask.evaluate(execution);
    expect(result.passed).toBe(true);
    expect(result.diagnostics?.map((diagnostic) => diagnostic.code)).toEqual([
      "large_output_recovery.read_recovery",
      "large_output_recovery.unbounded_read",
    ]);
  });

  test("accepts non-tool assistant blocks alongside one exact recovery tool call", async () => {
    const execution = await assembledExecution(DEFAULT_PROFILES[0]!, true);

    expect(largeOutputRecoveryTask.evaluate(execution)).toEqual({ passed: true });
  });

  test("accepts a bounded read window that contains the instructed fact line", async () => {
    const execution = await assembledExecution(DEFAULT_PROFILES[1]!, false, { offset: 495, limit: 15 });

    expect(execution.toolCalls[1]!.input).toEqual({
      file_path: "$TOOL_OUTPUT/full-output-000001.txt",
      offset: 495,
      limit: 15,
    });
    expect(largeOutputRecoveryTask.evaluate(execution)).toEqual({ passed: true });
  });

  test("accepts provider-native thinking beside the exact final hidden fact", async () => {
    const execution = await assembledExecution(DEFAULT_PROFILES[1]!, false, { offset: 501, limit: 1 }, true);

    const final = execution.turns[0]!.messages.at(-1)!;
    expect(final.role).toBe("assistant");
    if (final.role !== "assistant") throw new Error("Expected an assistant final message.");
    expect(final.content.map((block) => block.type)).toEqual(["thinking", "text"]);
    expect(largeOutputRecoveryTask.evaluate(execution)).toEqual({ passed: true });
  });

  test("accepts a single labeled Markdown authorization value and rejects extra prose", async () => {
    const execution = await assembledExecution(DEFAULT_PROFILES[1]!);
    const final = execution.turns[0]!.messages.at(-1)!;
    if (final.role !== "assistant" || final.content[0]?.type !== "text")
      throw new Error("Expected an assistant final text block.");
    final.content[0].text = `The authorization value is:\n\n\`${execution.world.hiddenFact}\``;
    expect(largeOutputRecoveryTask.evaluate(execution)).toEqual({ passed: true });

    final.content[0].text += "\nUse it carefully.";
    expect(largeOutputRecoveryTask.evaluate(execution)).toMatchObject({
      passed: false,
      code: "large_output_recovery.final_format",
    });
  });

  test("accepts the declared authorization label and value on one line", async () => {
    const execution = await assembledExecution(DEFAULT_PROFILES[1]!);
    const final = execution.turns[0]!.messages.at(-1)!;
    if (final.role !== "assistant" || final.content[0]?.type !== "text")
      throw new Error("Expected an assistant final text block.");
    final.content[0].text = `The authorization value is: ${execution.world.hiddenFact}`;

    expect(largeOutputRecoveryTask.evaluate(execution)).toEqual({ passed: true });
  });
});

async function assembledExecution(
  profile: EvalProfile,
  includeProgressText = false,
  readWindow: { offset: number; limit: number } = { offset: 501, limit: 1 },
  includeFinalThinking = false,
): Promise<RuntimeEvalExecution<LargeOutputRecoveryWorld>> {
  const seed = "shared-seed-123";
  let call = 0;
  const result = await runRuntimeEvalExecution({
    task: largeOutputRecoveryTask,
    seed,
    profile,
    streamFunction(model, context, options) {
      call += 1;
      let response: Message;
      if (call === 1) {
        response = assistantMessage(
          [
            ...(includeProgressText
              ? [{ type: "text" as const, text: "Retrieving the bounded archived record." }]
              : []),
            {
              type: "tool_call",
              id: "archive-fixture-1",
              name: "retrieve_archived_record",
              input: { request_id: token(seed, "ARCHIVE_REQUEST") },
            },
          ],
          "tool_use",
        );
      } else if (call === 2) {
        const resultMessage = context.messages.findLast(
          (message) => message.role === "tool_result" && message.toolName === "retrieve_archived_record",
        ) as (Message & { metadata?: { fullOutputPath?: string } }) | undefined;
        const fullOutputPath = resultMessage?.metadata?.fullOutputPath;
        if (!fullOutputPath) throw new Error("Missing dynamic full-output path in persisted tool result.");
        response = assistantMessage(
          [
            {
              type: "tool_call",
              id: "archive-read-1",
              name: "read",
              input: { file_path: fullOutputPath, ...readWindow },
            },
          ],
          "tool_use",
        );
      } else {
        expect(JSON.stringify(context.messages)).toContain(token(seed, "RECOVERY_FACT"));
        response = assistantMessage([
          ...(includeFinalThinking
            ? [{ type: "thinking" as const, thinking: "The exact recovered value is ready." }]
            : []),
          { type: "text", text: token(seed, "RECOVERY_FACT") },
        ]);
      }
      return sequenceStream([response])(model, context, options);
    },
  });
  expect(
    result.failures,
    JSON.stringify({
      core: result.execution.turns[0]?.coreEvents.map((value) => value.event.type),
      runtime: result.execution.turns[0]?.runtimeEvents.map((value) => (value as { type?: string }).type),
      notifications: result.execution.turns[0]?.notifications.map((value) => value.method),
    }),
  ).toEqual([]);
  return result.execution as RuntimeEvalExecution<LargeOutputRecoveryWorld>;
}

function token(seed: string, prefix: string): string {
  return `${prefix}_${seed.replace(/[^a-zA-Z0-9]/g, "").slice(0, 10)}`;
}

function setFinalText(value: RuntimeEvalExecution<LargeOutputRecoveryWorld>, text: string): void {
  const final = value.turns[0]!.messages.at(-1)!;
  if (final.role !== "assistant") throw new Error("Missing final assistant message.");
  final.content = [{ type: "text", text }];
}
